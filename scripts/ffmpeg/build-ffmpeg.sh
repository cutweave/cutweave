#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
#
# Configures, builds and installs the pinned FFmpeg as shared libraries into $CW_WORK/stage
# (WP-0A.06) and records the exact configure line in $CW_WORK/configure.txt.
#
# --disable-autodetect makes the configure line the complete feature list: nothing is picked up
# from whatever happens to be installed, and configure fails if any explicitly enabled library
# or hwaccel is missing.
#
# Usage: scripts/ffmpeg/build-ffmpeg.sh   (after build-deps.sh; environment: see lib.sh)

set -euo pipefail
# shellcheck source=lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
cw_init

[ -f "$CW_PREFIX/.cutweave-deps" ] || cw_die "no dependencies in $CW_PREFIX; run build-deps.sh first"

args=(
  --prefix="$CW_STAGE"
  --enable-shared
  --disable-static
  --enable-gpl
  --enable-version3
  --disable-autodetect
  --disable-doc
  --disable-debug
  --disable-ffplay
  --pkg-config-flags=--static
  --extra-cflags="-I$CW_PREFIX/include"
  --extra-ldflags="-L$CW_PREFIX/lib"
  --extra-libs="$(cw_cxx_libs)"
  --enable-zlib
  # Required by WP-0A.06 (libvidstab: resolution R6).
  --enable-libx264
  --enable-libx265
  --enable-libsvtav1
  --enable-libvpx
  --enable-libopus
  --enable-libmp3lame
  --enable-libvidstab
  --enable-libzimg
  --enable-libsoxr
  --enable-libass
  # Software AV1 decoding, and the text stack libass already needs (drawtext filter).
  --enable-libdav1d
  --enable-libfreetype
  --enable-libfribidi
  --enable-libharfbuzz
)

case "$CW_OS" in
  windows)
    args+=(
      --arch=x86_64
      --enable-w32threads
      --extra-ldflags=-static-libgcc
      --enable-d3d11va
      --enable-d3d12va
      --enable-dxva2
      --enable-mediafoundation
      --enable-ffnvcodec
      --enable-cuvid
      --enable-nvdec
      --enable-nvenc
      --enable-amf
      --enable-libvpl
    )
    cw_msvc_lib_on_path ||
      cw_warn "MSVC lib.exe not found: avcodec.lib etc. are generated by dlltool instead"
    ;;
  macos)
    args+=(
      --enable-pthreads
      --enable-iconv
      --enable-videotoolbox
      --enable-audiotoolbox
      # Relocatable: libraries are @rpath/libavX.N.dylib, programs look in ../lib.
      --install-name-dir=@rpath
      --extra-ldexeflags=-Wl,-rpath,@executable_path/../lib
      --extra-ldsoflags=-Wl,-rpath,@loader_path
    )
    ;;
  linux)
    # Relocatable rpaths ($ORIGIN) are set with patchelf by package.sh.
    args+=(
      --enable-pthreads
      --enable-pic
      --enable-iconv
      --enable-vaapi
      --enable-vdpau
      --enable-libdrm
      --enable-ffnvcodec
      --enable-cuvid
      --enable-nvdec
      --enable-nvenc
      --enable-libvpl
    )
    ;;
esac

# In-tree: an out-of-tree build would put SRC_PATH=C:/... into make's colon-separated vpath.
src="$(cw_extract ffmpeg)"
rm -rf "$CW_STAGE"
cd "$src"

printf '%q ' ./configure "${args[@]}" | sed 's/ $//' >"$CW_WORK/configure.txt"
echo >>"$CW_WORK/configure.txt"
cw_log "configure: $(cat "$CW_WORK/configure.txt")"
if ! ./configure "${args[@]}"; then
  tail -n 60 ffbuild/config.log >&2 || true
  cw_die "FFmpeg configure failed (full log: $src/ffbuild/config.log)"
fi

cw_log "building FFmpeg $CW_VERSION with $CW_JOBS jobs"
make -j"$CW_JOBS"
make install
cw_log "FFmpeg installed in $CW_STAGE"
