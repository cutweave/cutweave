//! Generated artifacts (arch §5.3): the JSON Schema catalogs and the TypeScript types + client.
//!
//! Everything is derived from the [`Registry`], so the codegen binary must link every crate
//! that registers commands (see `s5-ops`'s `s5-codegen`).

use std::{borrow::Cow, fmt::Write as _};

use serde_json::{Value, json};
use specta::{Type, Types, datatype::DataType};
use specta_typescript::{Exporter, Typescript};

use crate::{
    error::CmdError,
    registry::{EntryKind, Registry, output_schema},
    time::FLICKS_PER_SECOND,
};

/// JSON Schema dialect of every schema in the catalogs (also the MCP 2025-11-25 default).
pub const SCHEMA_DIALECT: &str = "https://json-schema.org/draft/2020-12/schema";

/// A generated file: path relative to the spike root, and contents.
pub struct Artifact {
    /// e.g. `schema/commands.json`.
    pub path: &'static str,
    /// File contents (LF line endings, trailing newline).
    pub contents: String,
}

/// All generated files.
pub fn artifacts(registry: &Registry) -> Result<Vec<Artifact>, specta_typescript::Error> {
    Ok(vec![
        Artifact {
            path: "schema/commands.json",
            contents: pretty(&catalog(registry, EntryKind::Command)),
        },
        Artifact {
            path: "schema/queries.json",
            contents: pretty(&catalog(registry, EntryKind::Query)),
        },
        Artifact {
            path: "ts/src/generated/commands.ts",
            contents: typescript(registry)?,
        },
    ])
}

fn pretty(v: &Value) -> String {
    let mut s = serde_json::to_string_pretty(v).unwrap_or_default();
    s.push('\n');
    s
}

/// The error schema: `CmdError` (tagged by `code`) plus the human `message`.
#[must_use]
pub fn error_schema() -> Value {
    json!({
        "allOf": [
            output_schema::<CmdError>(),
            {
                "type": "object",
                "properties": { "message": { "type": "string" } },
                "required": ["message"]
            }
        ]
    })
}

/// The JSON Schema catalog of all commands (or all queries).
#[must_use]
pub fn catalog(registry: &Registry, kind: EntryKind) -> Value {
    let entries: Vec<Value> = registry
        .iter()
        .filter(|e| e.meta.kind == kind)
        .map(|e| {
            json!({
                "name": e.meta.name,
                "summary": e.meta.summary,
                "undoable": e.meta.undoable,
                "ui_only": e.meta.ui_only,
                "engine_op": e.is_engine_op(),
                "mcp": {
                    "tier": e.meta.mcp,
                    "tool": e.meta.mcp_tool_name(),
                    "annotations": e.meta.annotations,
                },
                "params": e.params_schema(),
                "output": e.output_schema(),
            })
        })
        .collect();
    json!({
        "$schema": SCHEMA_DIALECT,
        "$comment": "GENERATED by `cargo run -p s5-ops --bin s5-codegen`. Do not edit; snapshot-tested.",
        "kind": match kind { EntryKind::Command => "commands", EntryKind::Query => "queries" },
        "error": error_schema(),
        "entries": entries,
    })
}

const HEADER: &str = "// GENERATED by `cargo run -p s5-ops --bin s5-codegen` from the s5 command registry.\n\
// Do not edit. Snapshot-tested (ops/tests/snapshots) and typechecked (ops/tests/typescript.rs).";

/// TypeScript: specta-exported types plus a `Commands` map and a typed `CutweaveClient`.
pub fn typescript(registry: &Registry) -> Result<String, specta_typescript::Error> {
    let mut types = Types::default();
    let mut entries: Vec<(&'static str, EntryKind, DataType, DataType)> = Vec::new();
    for e in registry.iter() {
        let (params, output) = e.ts_types(&mut types);
        entries.push((e.meta.name, e.meta.kind, params, output));
    }
    let error = CmdError::definition(&mut types);

    let exporter = Exporter::from(Typescript::default())
        .header(HEADER)
        .framework_prelude("")
        .framework_runtime(move |mut ctx| {
            let mut out = String::new();
            let _ = writeln!(out, "/** Flicks per second (1 flick = 1/705600000 s). `Time` values are integer flicks. */");
            let _ = writeln!(out, "export const FLICKS_PER_SECOND = {FLICKS_PER_SECOND};\n");
            let _ = writeln!(out, "/** Every registered command and query: wire name -> params/output types. */");
            let _ = writeln!(out, "export type Commands = {{");
            for (name, kind, params, output) in &entries {
                let kind = match kind {
                    EntryKind::Command => "command",
                    EntryKind::Query => "query",
                };
                let _ = writeln!(
                    out,
                    "  {name:?}: {{ kind: {kind:?}; params: {}; output: {} }};",
                    ctx.reference(params)?,
                    ctx.reference(output)?
                );
            }
            let _ = writeln!(out, "}};\n");
            let _ = writeln!(out, "/** Error payload: the typed error plus a human-readable message. */");
            let _ = writeln!(out, "export type WireError = {} & {{ message: string }};\n", ctx.reference(&error)?);
            out.push_str(CLIENT_RUNTIME);
            out.push('\n');
            out.push_str(&ctx.render_types()?);
            Ok(Cow::Owned(out))
        });
    let mut ts = exporter.export(&types, specta_serde::Format)?;
    if !ts.ends_with('\n') {
        ts.push('\n');
    }
    Ok(ts)
}

const CLIENT_RUNTIME: &str = r#"export type CommandName = keyof Commands;
export type Params<K extends CommandName> = Commands[K]["params"];
export type Output<K extends CommandName> = Commands[K]["output"];

/** Per-call envelope options (arch §5.1). The actor is derived from the credential, never sent. */
export type CallOptions = {
  /** Client-generated UUIDv7; a retry with the same id returns the original result. */
  requestId?: string;
  /** Fail with `conflict` unless the document is at this revision. */
  expectedRev?: number;
  /** Apply, return the result, roll back. */
  dryRun?: boolean;
};

export type RpcRequest = {
  name: CommandName;
  params: unknown;
  request_id?: string;
  expected_rev?: number;
  dry_run?: boolean;
};

export type RpcReply =
  | { ok: true; rev: number; result: unknown; dry_run: boolean; deduplicated: boolean }
  | { ok: false; error: WireError };

/** Moves one request to the engine (JSON-RPC over WebSocket, MCP, in-process, ...). */
export interface Transport {
  send(request: RpcRequest): Promise<RpcReply>;
}

export class CutweaveError extends Error {
  readonly error: WireError;
  constructor(error: WireError) {
    super(error.message);
    this.error = error;
  }
}

/** Typed client: `call("clip.split", { item, at })` is checked against the registry at compile time. */
export class CutweaveClient {
  readonly #transport: Transport;
  constructor(transport: Transport) {
    this.#transport = transport;
  }

  async call<K extends CommandName>(
    name: K,
    params: Params<K>,
    options: CallOptions = {},
  ): Promise<Output<K>> {
    const request: RpcRequest = { name, params };
    if (options.requestId !== undefined) request.request_id = options.requestId;
    if (options.expectedRev !== undefined) request.expected_rev = options.expectedRev;
    if (options.dryRun !== undefined) request.dry_run = options.dryRun;
    const reply = await this.#transport.send(request);
    if (!reply.ok) throw new CutweaveError(reply.error);
    return reply.result as Output<K>;
  }
}
"#;
