//! The command registry: everything the MCP server (WP-0H.02), RPC and CLI need to enumerate,
//! describe and invoke commands without knowing their Rust types.
//!
//! Entries are submitted at link time by `#[command]` / `#[query]` via `inventory` and collected
//! once into [`Registry::global`]. Each [`CommandEntry`] carries:
//!
//! - [`CommandMeta`]: name, summary, kind, undoable, MCP tier, MCP annotations;
//! - params/output JSON Schemas (schemars, draft 2020-12, fully inlined, direction-aware);
//! - specta type hooks for TS generation;
//! - a type-erased runner `Value -> Result<Value, CmdError>` dispatched by [`crate::Engine`].

use std::{collections::BTreeMap, sync::OnceLock};

use schemars::{JsonSchema, generate::SchemaSettings};
use serde::{Serialize, de::DeserializeOwned};
use serde_json::Value;
use specta::{Types, datatype::DataType};

use crate::{
    doc::Doc,
    engine::{Caller, Engine},
    error::{CmdError, decode, encode},
    tx::Tx,
};

/// Command vs query.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum EntryKind {
    /// Mutates the document (journaled, deduplicated, maybe undoable).
    Command,
    /// Read-only.
    Query,
}

/// MCP exposure tier (arch §14, ADR-009).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum McpTier {
    /// Always listed as its own tool.
    Core,
    /// Reachable via search/describe/execute only.
    Catalog,
    /// Not reachable from MCP (UI/internal).
    Hidden,
}

/// MCP tool annotations (hints) derived from macro metadata.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[allow(clippy::struct_excessive_bools)]
pub struct Annotations {
    /// `readOnlyHint` (true exactly for queries).
    pub read_only: bool,
    /// `destructiveHint`.
    pub destructive: bool,
    /// `idempotentHint`.
    pub idempotent: bool,
    /// `openWorldHint` (false: the engine is a closed local world).
    pub open_world: bool,
}

impl Serialize for Annotations {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        // Serialized with MCP's field names so 0H.02 can pass them through verbatim.
        use serde::ser::SerializeStruct;
        let mut st = s.serialize_struct("Annotations", 4)?;
        st.serialize_field("readOnlyHint", &self.read_only)?;
        st.serialize_field("destructiveHint", &self.destructive)?;
        st.serialize_field("idempotentHint", &self.idempotent)?;
        st.serialize_field("openWorldHint", &self.open_world)?;
        st.end()
    }
}

/// Static metadata generated by the macros.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
pub struct CommandMeta {
    /// Wire name, `namespace.verb_object`.
    pub name: &'static str,
    /// One-line summary (MCP tool description).
    pub summary: &'static str,
    /// Command or query.
    pub kind: EntryKind,
    /// UI-only scope (arch §6, `#[command(scope = "ui")]`): only the UI credential may invoke it;
    /// the engine refuses every other caller with `forbidden`.
    pub ui_only: bool,
    /// Whether applying it pushes an undo entry.
    pub undoable: bool,
    /// MCP tier.
    pub mcp: McpTier,
    /// MCP annotations.
    pub annotations: Annotations,
    /// Rust type name of the params struct (diagnostics only).
    pub rust_type: &'static str,
}

impl CommandMeta {
    /// MCP tool name (`clip.split` -> `clip_split`), matching the arch §14 tool list.
    #[must_use]
    pub fn mcp_tool_name(&self) -> String {
        self.name.replace('.', "_")
    }
}

/// Implemented by the macros: the static metadata of a params type.
pub trait Described {
    /// Metadata.
    const META: CommandMeta;
}

/// Types that cross the wire: serializable, JSON-Schema-describable and TS-exportable.
pub trait WireType: Serialize + JsonSchema + specta::Type + 'static {}
impl<T: Serialize + JsonSchema + specta::Type + 'static> WireType for T {}

/// A document command. Write `impl Command for X` next to `#[command] struct X`.
#[diagnostic::on_unimplemented(
    message = "`{Self}` is marked #[command] but does not implement `s5_bus::Command`",
    note = "add `impl Command for {Self} {{ type Output = ...; fn apply(&self, tx: &mut Tx<'_>) -> Result<Self::Output, CmdError> {{ ... }} }}`"
)]
pub trait Command: Described + DeserializeOwned + WireType {
    /// Result type (serialized as the call result).
    type Output: WireType;
    /// Applies the command. All mutation goes through `tx`; returning `Err` rolls back.
    fn apply(&self, tx: &mut Tx<'_>) -> Result<Self::Output, CmdError>;
}

/// A read-only query. It receives `&Doc`, so it cannot mutate by construction.
#[diagnostic::on_unimplemented(
    message = "`{Self}` is marked #[query] but does not implement `s5_bus::Query`",
    note = "add `impl Query for {Self} {{ type Output = ...; fn run(&self, doc: &Doc) -> Result<Self::Output, CmdError> {{ ... }} }}`"
)]
pub trait Query: Described + DeserializeOwned + WireType {
    /// Result type.
    type Output: WireType;
    /// Runs the query against a document snapshot.
    fn run(&self, doc: &Doc) -> Result<Self::Output, CmdError>;
}

/// An engine-level operation (history, project lifecycle) that needs more than a `Tx`.
#[diagnostic::on_unimplemented(
    message = "`{Self}` is marked #[command(engine)] but does not implement `s5_bus::EngineOp`"
)]
pub trait EngineOp: Described + DeserializeOwned + WireType {
    /// Result type.
    type Output: WireType;
    /// Runs against the engine on behalf of `caller`.
    fn run(&self, engine: &mut Engine, caller: &Caller) -> Result<Self::Output, CmdError>;
}

/// Type-erased runner.
#[derive(Clone, Copy)]
pub(crate) enum Runner {
    Command(fn(&mut Tx<'_>, Value) -> Result<Value, CmdError>),
    Query(fn(&Doc, Value) -> Result<Value, CmdError>),
    Engine(fn(&mut Engine, &Caller, Value) -> Result<Value, CmdError>),
}

/// One registry entry. Built in const context by the macros and submitted via `inventory`.
pub struct CommandEntry {
    /// Metadata.
    pub meta: CommandMeta,
    pub(crate) runner: Runner,
    params_schema: fn() -> Value,
    output_schema: fn() -> Value,
    ts: fn(&mut Types) -> (DataType, DataType),
}

inventory::collect!(CommandEntry);

fn run_command<C: Command>(tx: &mut Tx<'_>, params: Value) -> Result<Value, CmdError> {
    let cmd: C = decode(params)?;
    encode(&cmd.apply(tx)?)
}

fn run_query<Q: Query>(doc: &Doc, params: Value) -> Result<Value, CmdError> {
    let q: Q = decode(params)?;
    encode(&q.run(doc)?)
}

fn run_engine_op<E: EngineOp>(
    engine: &mut Engine,
    caller: &Caller,
    params: Value,
) -> Result<Value, CmdError> {
    let op: E = decode(params)?;
    encode(&op.run(engine, caller)?)
}

fn schema_settings() -> SchemaSettings {
    // Fully inlined (no `$ref`/`$defs`): every tool schema is self-contained, which is the most
    // portable form for MCP clients. `$schema` is stated once at the catalog root.
    SchemaSettings::draft2020_12().with(|s| {
        s.inline_subschemas = true;
        s.meta_schema = None;
    })
}

/// Params schema (deserialize contract: e.g. `Time` also accepts timecode strings).
#[must_use]
pub fn input_schema<T: JsonSchema>() -> Value {
    schema_settings()
        .for_deserialize()
        .into_generator()
        .into_root_schema_for::<T>()
        .to_value()
}

/// Output schema (serialize contract: `Time` is an integer).
#[must_use]
pub fn output_schema<T: JsonSchema>() -> Value {
    schema_settings()
        .for_serialize()
        .into_generator()
        .into_root_schema_for::<T>()
        .to_value()
}

fn ts_pair<P: specta::Type, O: specta::Type>(types: &mut Types) -> (DataType, DataType) {
    (P::definition(types), O::definition(types))
}

impl CommandEntry {
    #[doc(hidden)]
    #[must_use]
    pub const fn command<C: Command>() -> CommandEntry {
        CommandEntry {
            meta: C::META,
            runner: Runner::Command(run_command::<C>),
            params_schema: input_schema::<C>,
            output_schema: output_schema::<C::Output>,
            ts: ts_pair::<C, C::Output>,
        }
    }

    #[doc(hidden)]
    #[must_use]
    pub const fn query<Q: Query>() -> CommandEntry {
        CommandEntry {
            meta: Q::META,
            runner: Runner::Query(run_query::<Q>),
            params_schema: input_schema::<Q>,
            output_schema: output_schema::<Q::Output>,
            ts: ts_pair::<Q, Q::Output>,
        }
    }

    #[doc(hidden)]
    #[must_use]
    pub const fn engine_op<E: EngineOp>() -> CommandEntry {
        CommandEntry {
            meta: E::META,
            runner: Runner::Engine(run_engine_op::<E>),
            params_schema: input_schema::<E>,
            output_schema: output_schema::<E::Output>,
            ts: ts_pair::<E, E::Output>,
        }
    }

    /// Wire name.
    #[must_use]
    pub fn name(&self) -> &'static str {
        self.meta.name
    }

    /// JSON Schema of the params object (root `type: object`, `additionalProperties: false`).
    #[must_use]
    pub fn params_schema(&self) -> Value {
        (self.params_schema)()
    }

    /// JSON Schema of the result.
    #[must_use]
    pub fn output_schema(&self) -> Value {
        (self.output_schema)()
    }

    /// Registers the params/output TS types and returns references to them.
    pub fn ts_types(&self, types: &mut Types) -> (DataType, DataType) {
        (self.ts)(types)
    }

    /// Invokes this entry on `engine` (convenience for `engine.invoke` with this name).
    pub fn invoke(
        &self,
        engine: &mut Engine,
        caller: &Caller,
        params: Value,
    ) -> Result<crate::engine::Response, CmdError> {
        engine.invoke(caller, crate::engine::Request::new(self.meta.name, params))
    }

    /// Whether this entry is an engine op (not allowed inside batches).
    #[must_use]
    pub fn is_engine_op(&self) -> bool {
        matches!(self.runner, Runner::Engine(_))
    }
}

/// Registry construction failure (duplicate names are a programming error).
#[derive(Debug, thiserror::Error)]
pub enum RegistryError {
    /// Two entries share a wire name or MCP tool name.
    #[error("duplicate registry name `{0}`")]
    Duplicate(String),
    /// A params/output schema root is not an object (MCP requires `type: object` for both).
    #[error("`{0}`: {1} schema root must be a JSON object (wrap the type in a struct)")]
    NotAnObject(String, &'static str),
}

/// All registered entries, sorted by name.
pub struct Registry {
    entries: BTreeMap<&'static str, &'static CommandEntry>,
}

impl Registry {
    /// Collects every `inventory`-submitted entry linked into this binary.
    ///
    /// Note: entries from a crate that is never referenced by the final binary are not linked;
    /// the binary must use something from every crate that registers commands.
    pub fn collect() -> Result<Registry, RegistryError> {
        let mut entries = BTreeMap::new();
        let mut tools = std::collections::BTreeSet::new();
        for entry in inventory::iter::<CommandEntry> {
            if entries.insert(entry.meta.name, entry).is_some() {
                return Err(RegistryError::Duplicate(entry.meta.name.into()));
            }
            if !tools.insert(entry.meta.mcp_tool_name()) {
                return Err(RegistryError::Duplicate(entry.meta.mcp_tool_name()));
            }
            // The macro guarantees object params; outputs are arbitrary types, so check here.
            for (which, schema) in [
                ("params", entry.params_schema()),
                ("output", entry.output_schema()),
            ] {
                if schema.get("type").and_then(Value::as_str) != Some("object") {
                    return Err(RegistryError::NotAnObject(entry.meta.name.into(), which));
                }
            }
        }
        Ok(Registry { entries })
    }

    /// The process-wide registry.
    ///
    /// # Panics
    /// On duplicate names (a build-time mistake that tests catch).
    pub fn global() -> &'static Registry {
        static GLOBAL: OnceLock<Registry> = OnceLock::new();
        GLOBAL.get_or_init(|| Registry::collect().unwrap_or_else(|e| panic!("{e}")))
    }

    /// Entries sorted by name.
    pub fn iter(&self) -> impl Iterator<Item = &'static CommandEntry> + '_ {
        self.entries.values().copied()
    }

    /// Lookup by wire name.
    #[must_use]
    pub fn get(&self, name: &str) -> Option<&'static CommandEntry> {
        self.entries.get(name).copied()
    }

    /// Lookup by MCP tool name (`clip_split`).
    #[must_use]
    pub fn get_by_tool_name(&self, tool: &str) -> Option<&'static CommandEntry> {
        self.iter().find(|e| e.meta.mcp_tool_name() == tool)
    }

    /// Number of entries.
    #[must_use]
    pub fn len(&self) -> usize {
        self.entries.len()
    }

    /// Whether empty.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }
}
