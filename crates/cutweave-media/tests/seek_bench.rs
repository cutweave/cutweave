//! Seek latency on the CPU path (WP-1D.03; arch §19, ADR-0003): recorded, not gated. ADR-0003
//! expects CPU decode to miss the 150 ms 4K long-GOP budget; hardware decode (WP-1D.04) and
//! proxies close it.
//!
//! `cargo nextest run -p cutweave-media --features ffmpeg --test seek_bench --run-ignored
//! ignored-only --no-capture` prints, per file, p50/p95/max of
//! - **cold** seeks: the decoder first sits on frame 0, so every seek decodes forward from its
//!   keyframe (the S3 bench's cold seek);
//! - **random** seeks through one decoder, as a scrubbing UI issues them (forward seeks inside
//!   the decoder's reach continue instead of seeking);
//! - **steps**: single-frame steps forward.
//!
//! Latency is request to a decoded frame in CPU memory in its native layout (no upload). The
//! 60 s 4K clip is generated by the probe/index tests (`probe_index.rs`) on first use.
#![cfg(feature = "ffmpeg")]
#![allow(clippy::unwrap_used, clippy::expect_used)]

mod support;

use std::sync::Arc;
use std::time::Instant;

use cutweave_media::{DecodeOpts, MediaBackend};
use support::Rng;

const SEEKS: usize = 60;

/// Cancel latency of a pending 4K long-GOP seek (WBS: within 10 ms), measured alone.
///
/// - **Pooled** (the production path): the lease waits for the decoder thread's answer or its
///   token, and `cancel()` wakes it, so a cancel returns as soon as the waiting thread runs,
///   whatever FFmpeg is doing. Asserted: p95 under 10 ms.
/// - **Direct** (`open_decoder` called on this thread): the decoder polls between packets, so a
///   cancel waits for the FFmpeg call in progress (a frame-threaded flush waits for every frame
///   in flight). Printed only.
#[test]
#[ignore = "benchmark: run alone with --run-ignored ignored-only --no-capture"]
fn cancel_latency_of_pending_4k_seeks() {
    let Some((direct, pooled)) = support::pending_4k_cancels(10) else {
        return;
    };
    support::show_latencies("direct decoder, pending 4K seeks", &direct);
    let (_, p95, _) = support::show_latencies("pooled lease, pending 4K seeks", &pooled);
    assert!(p95 < 10.0, "pooled cancel latency p95 {p95:.2} ms");
}

#[test]
#[ignore = "benchmark: run with --run-ignored ignored-only --no-capture"]
#[allow(clippy::cast_precision_loss)]
fn seek_latency_on_the_cpu_path() {
    for name in [
        "h264_4k30_longgop_60s.mp4",
        "h264_4k30_longgop.mp4",
        "hevc_10bit_sdr.mp4",
        "prores_422hq_1080p.mov",
        "h264_1080p60.mp4",
    ] {
        let Some(path) = support::corpus_file(name) else {
            continue;
        };
        let backend = support::backend();
        let t0 = Instant::now();
        let index = Arc::new(backend.index_media(&path).unwrap());
        let index_ms = t0.elapsed().as_secs_f64() * 1e3;
        let opts = DecodeOpts::default().with_index(Arc::clone(&index));
        let frames = index.frame_count();
        let time = |n: usize| index.time_of(n).unwrap();
        let ms = |t: Instant| t.elapsed().as_secs_f64() * 1e3;
        let mut rng = Rng::new(support::seed(name));

        let mut d = backend.open_decoder(&path, &opts).unwrap();
        let mut cold = Vec::new();
        for _ in 0..SEEKS {
            let n = rng.below(frames);
            d.seek_exact(time(0)).unwrap();
            let t = Instant::now();
            d.seek_exact(time(n)).unwrap();
            cold.push(ms(t));
        }
        let mut d = backend.open_decoder(&path, &opts).unwrap();
        let mut random = Vec::new();
        for _ in 0..SEEKS {
            let n = rng.below(frames);
            let t = Instant::now();
            d.seek_exact(time(n)).unwrap();
            random.push(ms(t));
        }
        let mut steps = Vec::new();
        let start = rng.below(frames.saturating_sub(SEEKS).max(1));
        d.seek_exact(time(start)).unwrap();
        for n in start + 1..(start + SEEKS).min(frames) {
            let t = Instant::now();
            d.seek_exact(time(n)).unwrap();
            steps.push(ms(t));
        }
        let show = |v: &[f64]| {
            format!(
                "p50 {:.1} / p95 {:.1} / max {:.1} ms",
                support::percentile(v, 50.0),
                support::percentile(v, 95.0),
                support::percentile(v, 100.0)
            )
        };
        let (_, _, gop_max, _) = index.gop_stats();
        eprintln!(
            "{name}: {frames} frames, GOP up to {gop_max}, index {index_ms:.0} ms | cold {} | \
             random {} | step {}",
            show(&cold),
            show(&random),
            show(&steps)
        );
    }
}
