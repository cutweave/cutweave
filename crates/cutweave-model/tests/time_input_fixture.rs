//! WP-1M.07: the shared `TimeInput` fixture file. The Rust parser is the reference; this test
//! computes the expected result of every case and checks it against
//! `tests/fixtures/time-input.json`, which the editor's TypeScript `parseTimeInput` is tested
//! against (`packages/editor/src/time/timeInput.test.ts`). `CUTWEAVE_BLESS=1 cargo test -p
