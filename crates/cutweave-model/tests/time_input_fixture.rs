fn rate_json(rate: Option<FrameRate>) -> Value {
    rate.map_or(Value::Null, |r| json!({ "num": r.num(), "den": r.den() }))
}

fn case(input: &str, rate: Option<FrameRate>) -> Value {
    let flicks = input
        .parse::<TimeInput>()
        .and_then(|t| t.resolve(rate))
        .ok()
        .map(|t| t.flicks());
    json!({ "input": input, "rate": rate_json(rate), "flicks": flicks })
}

fn generate() -> Value {
    let mut cases = Vec::new();
    for input in ABSOLUTE {
        cases.push(case(input, None));
    }
    // Frame-based forms without a rate must all be refused ...
    for input in ["f:1500", "00:00:02:00", "00:01:00;02"] {
        cases.push(case(input, None));
    }
    // ... and resolve at every common rate.
    for rate in FrameRate::COMMON {
        for input in FRAME_BASED {
            cases.push(case(input, Some(rate)));
        }
    }
    // Absolute forms ignore the rate.
    for input in ["62.5s", "42", "-2s"] {
        cases.push(case(input, Some(FrameRate::FPS_30)));
    }
    json!({
        "comment": "Generated by crates/cutweave-model/tests/time_input_fixture.rs; do not edit. flicks is null when the input is refused.",
        "cases": cases,
    })
}

fn fixture_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/time-input.json")
}

#[test]
fn time_input_fixture_matches_the_parser() {
    let mut text = serde_json::to_string_pretty(&generate()).unwrap();
    text.push('\n');
    let path = fixture_path();
    if std::env::var_os("CUTWEAVE_BLESS").is_some() {
        fs::write(&path, &text).unwrap();
        return;
    }
    let on_disk = fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    assert!(
        on_disk == text,
        "{} is out of date: run `CUTWEAVE_BLESS=1 cargo test -p cutweave-model --test time_input_fixture`",
        path.display()
    );
}

#[test]
fn the_fixture_has_enough_valid_and_invalid_cases() {
    let cases = generate()["cases"].as_array().unwrap().clone();
    let valid = cases.iter().filter(|c| !c["flicks"].is_null()).count();
    assert!(cases.len() >= 40 && valid >= 40 && cases.len() - valid >= 20);
}
