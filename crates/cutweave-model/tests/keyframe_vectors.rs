//! WP-2C.02: every row of `docs/spec/keyframes-vectors.json` (keyframes §12), from Rust.
//!
//! - `presets`: [`Easing::preset`] reproduces the §4.6 table, in its order.
//! - `easing` (E): [`Interp::progress`] within the file's tolerance (linear rows bit-exact).
//! - `eval` (V): [`Animatable::eval`] plus the property clamp (§7); `"exact": true` rows as f64
//!   equality.
//! - `retime` (R): the §8.1 split and trim rules ([`Animatable::split`], `trim_start`,
//!   `trim_end`), structurally identical to the reference.
//! - `ops` (O): the key-list primitives behind `keyframe.set/delete/move/clear` (§9), with
//!   `t`/`at` snapped on the sequence's frame grid (§3.2).
//! - `invalid` (X): construction rejects each document with the invariant it breaks (§3.3).
//!
//! The file is generated by `docs/spec/keyframes_ref.py` (`just spec-check` keeps it current).

// Exact rows compare floats bit for bit on purpose.
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::float_cmp)]

use std::{fs, path::PathBuf};

use cutweave_model::{
    AnimValue, Animatable, Color, Duration, Easing, FrameRate, Interp, PropId, Rounding,
    ShortestAngle, Time, ValueRange, ValueType, Vec2,
};
use serde::Serialize;
use serde_json::Value;

fn vectors() -> Value {
    let path =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../docs/spec/keyframes-vectors.json");
    let text =
        fs::read_to_string(&path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    serde_json::from_str(&text).expect("the vectors file is JSON")
}

fn tolerance(doc: &Value) -> f64 {
    doc["tolerance"].as_f64().expect("tolerance")
}

fn rows<'a>(doc: &'a Value, section: &str) -> &'a [Value] {
    doc[section]
        .as_array()
        .unwrap_or_else(|| panic!("section {section}"))
}

fn time(v: &Value) -> Time {
    Time::from_flicks(v.as_i64().expect("integer flicks")).expect("a safe time")
}

/// Per-component comparison of two JSON values: integers (key times) exactly, numbers within
/// `tol` (or as f64 equality when `tol` is `None`), everything else structurally.
fn close(actual: &Value, expected: &Value, tol: Option<f64>) -> bool {
    match (actual, expected) {
        (Value::Number(a), Value::Number(b)) => {
            if let (Some(a), Some(b)) = (a.as_i64(), b.as_i64()) {
                return a == b;
            }
            let (a, b) = (a.as_f64().unwrap(), b.as_f64().unwrap());
            match tol {
                None => a == b,
                Some(tol) => (a - b).abs() <= tol,
            }
        }
        (Value::Object(a), Value::Object(b)) => {
            a.len() == b.len()
                && a.iter()
                    .all(|(k, v)| b.get(k).is_some_and(|w| close(v, w, tol)))
        }
        (Value::Array(a), Value::Array(b)) => {
            a.len() == b.len() && a.iter().zip(b).all(|(v, w)| close(v, w, tol))
        }
        _ => actual == expected,
    }
}

fn json<T: Serialize>(v: &T) -> Value {
    serde_json::to_value(v).expect("serializable")
}

#[test]
fn presets_reproduce_the_table_in_ui_order() {
    let doc = vectors();
    let table = doc["presets"].as_object().expect("presets");
    let names: Vec<&str> = table.keys().map(String::as_str).collect();
    let ours: Vec<&str> = Easing::PRESETS.iter().map(|e| e.name()).collect();
    assert_eq!(ours, names, "the presets in §4.6 order");
    for (name, stored) in table {
        let interp = Easing::preset(name).unwrap_or_else(|| panic!("preset {name}"));
        assert_eq!(
            interp.preset(),
            Some(name.as_str()),
            "{name} keeps its hint"
        );
        assert_eq!(json(&interp.clone().without_preset()), *stored, "{name}");
        assert_eq!(
            interp.matching_preset().map(Easing::name),
            Some(name.as_str())
        );
        let parsed = Interp::from_json(stored).expect("the table's interps are valid");
        assert_eq!(parsed, interp.clone().without_preset());
        let parsed_name: Easing = name.parse().expect("a preset is an easing name");
        assert_eq!(parsed_name.interp(), interp);
    }
    assert_eq!(
        Easing::preset("linear"),
        None,
        "linear and hold are not presets"
    );
    assert_eq!(Easing::preset("hold"), None);
    assert_eq!(Easing::preset("ease_out_2"), None);
    assert_eq!(
        "linear".parse::<Easing>().map(Easing::interp),
        Ok(Interp::Linear)
    );
    assert_eq!(
        "hold".parse::<Easing>().map(Easing::interp),
        Ok(Interp::Hold)
    );
}

#[test]
fn easing_rows() {
    let doc = vectors();
    let tol = tolerance(&doc);
    let mut failures = Vec::new();
    let mut worst = 0.0_f64;
    for row in rows(&doc, "easing") {
        let id = row["id"].as_str().unwrap();
        let interp = Interp::from_json(&row["interp"]).unwrap_or_else(|e| panic!("{id}: {e}"));
        let (dt, span) = (row["dt"].as_i64().unwrap(), row["span"].as_i64().unwrap());
        let got = interp.progress(dt, span);
        let want = row["expected"].as_f64().unwrap();
        let exact = row["exact"].as_bool().unwrap_or(false);
        let ok = if exact {
            got == want
        } else {
            (got - want).abs() <= tol
        };
        if !ok {
            failures.push(format!(
                "{id}: got {got:e}, want {want:e} ({:e} off)",
                got - want
            ));
        }
        worst = worst.max((got - want).abs());
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
    // The requirement is 1e-6; the spec's target for the solver and the spring is 1e-9 (§4.4).
    assert!(worst <= 1e-9, "worst easing error {worst:e}");
}

/// The evaluated value of an `eval` row, property-clamped when the row names a property.
fn eval_typed<T: AnimValue>(row: &Value) -> Value
where
    T::Eval: Serialize,
{
    let anim = Animatable::<T>::from_json(&row["animatable"]).expect("a valid animatable");
    let t = time(&row["t"]);
    let value = match row["prop"].as_str() {
        Some(prop) => anim.eval_clamped(t, prop.parse::<PropId>().expect("a prop").spec().clamp),
        None => anim.eval(t),
    };
    // The cursor evaluator and the bulk sampler return the same bits as `eval`.
    let raw = anim.eval(t);
    assert_eq!(anim.evaluator().eval(t), raw, "Evaluator == eval");
    assert_eq!(anim.eval_range(t, t, 1), vec![(t, raw)]);
    json(&value)
}

#[test]
fn eval_rows() {
    let doc = vectors();
    let tol = tolerance(&doc);
    let mut failures = Vec::new();
    for row in rows(&doc, "eval") {
        let id = row["id"].as_str().unwrap();
        let got = match row["type"].as_str().unwrap() {
            "scalar" | "angle" => eval_typed::<f64>(row),
            "angle_shortest" => eval_typed::<ShortestAngle>(row),
            "vec2" => eval_typed::<Vec2>(row),
            "bool" => eval_typed::<bool>(row),
            "color" => eval_typed::<Color>(row),
            other => panic!("{id}: unknown type {other}"),
        };
        let exact = row["exact"].as_bool().unwrap_or(false);
        // Within the file's tolerance, and in fact within the spec's 1e-9 target (§6).
        let tol = tol.min(1e-9);
        if !close(&got, &row["expected"], (!exact).then_some(tol)) {
            failures.push(format!("{id}: got {got}, want {}", row["expected"]));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

#[test]
fn retime_rows() {
    let doc = vectors();
    for row in rows(&doc, "retime") {
        let id = row["id"].as_str().unwrap();
        let anim = Animatable::<f64>::from_json(&row["animatable"]).expect("valid");
        let op = &row["op"];
        let duration = Duration::from_flicks(op["duration"].as_i64().unwrap()).unwrap();
        let prune = op["prune"].as_bool().unwrap_or(false);
        let got = match op["kind"].as_str().unwrap() {
            "split" => {
                let (left, right) = anim.split(time(&op["at"]), duration).expect("split");
                serde_json::json!({"left": json(&left), "right": json(&right)})
            }
            "trim_start" => json(
                &anim
                    .trim_start(time(&op["delta"]), duration, prune)
                    .expect("trim"),
            ),
            "trim_end" => {
                let new = Duration::from_flicks(op["new_duration"].as_i64().unwrap()).unwrap();
                json(&anim.trim_end(new, prune))
            }
            other => panic!("{id}: unknown op {other}"),
        };
        assert_eq!(got, row["expected"], "{id}: {}", row["note"]);
    }
}

/// Item time of a `set` row's key: `t` or `at`, snapped in sequence time (§3.2).
fn key_time(op: &Value) -> Time {
    let Some(rate) = op["rate"].as_array() else {
        return time(&op["t"]);
    };
    let rate = FrameRate::new(
        u32::try_from(rate[0].as_u64().unwrap()).unwrap(),
        u32::try_from(rate[1].as_u64().unwrap()).unwrap(),
    )
    .unwrap();
    let start = op["start"].as_i64().unwrap();
    let at = match op["at"].as_i64() {
        Some(at) => at,
        None => start + op["t"].as_i64().unwrap(),
    };
    let snapped = rate
        .snap_to_frame(Time::from_flicks(at).unwrap(), Rounding::Nearest)
        .unwrap();
    Time::from_flicks(snapped.flicks() - start).unwrap()
}

fn op_typed<T: AnimValue>(
    row: &Value,
    stored: ValueRange,
    clamp: ValueRange,
) -> Result<Value, String> {
    let anim = Animatable::<T>::from_json(&row["animatable"]).expect("valid");
    let op = &row["op"];
    let times = || -> Vec<Time> { op["ts"].as_array().unwrap().iter().map(time).collect() };
    let result = match op["kind"].as_str().unwrap() {
        "set" => {
            let value = op
                .get("value")
                .map(|v| serde_json::from_value::<T>(v.clone()).expect("a value"));
            let interp = op.get("easing").map(|e| {
                e.as_str()
                    .unwrap()
                    .parse::<Easing>()
                    .expect("an easing")
                    .interp()
            });
            anim.set_key(key_time(op), value, interp, stored, clamp)
        }
        "delete" => anim.delete_keys(&times()),
        "move" => anim.move_keys(&times(), time(&op["delta"])),
        "clear" => Ok(anim.cleared(op.get("t").map(time), clamp)),
        other => panic!("unknown op {other}"),
    };
    result.map(|a| json(&a)).map_err(|e| e.code().to_owned())
}

#[test]
fn ops_rows() {
    let doc = vectors();
    let tol = tolerance(&doc);
    for row in rows(&doc, "ops") {
        let id = row["id"].as_str().unwrap();
        let spec = row["prop"]
            .as_str()
            .unwrap()
            .parse::<PropId>()
            .unwrap()
            .spec();
        let got = match spec.value_type {
            ValueType::Scalar | ValueType::Angle => op_typed::<f64>(row, spec.stored, spec.clamp),
            ValueType::Vec2 => op_typed::<Vec2>(row, spec.stored, spec.clamp),
            ValueType::Bool => op_typed::<bool>(row, spec.stored, spec.clamp),
            other => panic!("{id}: no P2 property is {other:?}"),
        };
        match (&got, row.get("result"), row.get("error")) {
            (Ok(got), Some(want), None) => {
                assert!(close(got, want, Some(tol)), "{id}: got {got}, want {want}");
            }
            (Err(code), None, Some(want)) => assert_eq!(code, want, "{id}"),
            _ => panic!("{id}: got {got:?}, want {row}"),
        }
    }
}

fn invalid_typed<T: AnimValue>(row: &Value, stored: ValueRange) -> Option<String> {
    let anim = match Animatable::<T>::from_json(&row["animatable"]) {
        Ok(anim) => anim,
        Err(e) => return Some(e.code().to_owned()),
    };
    anim.check_range(stored).err().map(|e| e.code().to_owned())
}

#[test]
fn invalid_rows() {
    let doc = vectors();
    for row in rows(&doc, "invalid") {
        let id = row["id"].as_str().unwrap();
        let stored = row["prop"].as_str().map_or(ValueRange::ANY, |p| {
            p.parse::<PropId>().unwrap().spec().stored
        });
        let code = match row["type"].as_str().unwrap() {
            "scalar" => invalid_typed::<f64>(row, stored),
            "vec2" => invalid_typed::<Vec2>(row, stored),
            "bool" => invalid_typed::<bool>(row, stored),
            other => panic!("{id}: unknown type {other}"),
        };
        assert_eq!(
            code.as_deref(),
            row["error"].as_str(),
            "{id}: {}",
            row["note"]
        );
    }
}

#[test]
fn every_section_has_rows() {
    let doc = vectors();
    for (section, at_least) in [
        ("easing", 100),
        ("eval", 60),
        ("retime", 10),
        ("ops", 20),
        ("invalid", 14),
    ] {
        assert!(rows(&doc, section).len() >= at_least, "{section}");
    }
    assert_eq!(doc["presets"].as_object().unwrap().len(), 21);
}
