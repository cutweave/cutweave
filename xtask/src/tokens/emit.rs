//! Deterministic emitters: CSS, Tailwind `@theme`, TypeScript and Rust.

use std::fmt::Write as _;

use super::model::{Family, Rgba, ThemedToken, Tokens, alias_target};

const GENERATED: &str = "generated by `cargo xtask tokens` from design/tokens.json; do not edit";

/// Lower-cases `#hex`, turns `{alias}` into `var(--alias)`, leaves other values alone.
fn css_value(v: &str) -> String {
    match alias_target(v) {
        Some(a) => format!("var(--{a})"),
        None if v.starts_with('#') => v.to_ascii_lowercase(),
        None => v.to_owned(),
    }
}

fn themed_block(out: &mut String, selector: &str, tokens: &[&ThemedToken], theme: usize) {
    let _ = writeln!(out, "{selector} {{");
    for t in tokens {
        let _ = writeln!(out, "  --{}: {};", t.name, css_value(&t.values[theme]));
    }
    out.push_str("}\n");
}

/// `tokens.css`: custom properties per theme, `:root` families and type-style classes.
pub fn tokens_css(t: &Tokens) -> String {
    let themed: Vec<&ThemedToken> = t.colors.iter().chain(&t.shadows).collect();
    let mut out = format!("/* {} \u{2014} generated from tokens.json */\n", t.name);
    themed_block(
        &mut out,
        &format!(":root, [data-theme=\"{}\"]", t.themes[0]),
        &themed,
        0,
    );
    for (i, th) in t.themes.iter().enumerate().skip(1) {
        themed_block(&mut out, &format!("[data-theme=\"{th}\"]"), &themed, i);
    }
    out.push_str(":root {\n");
    for f in &t.families {
        for tok in &f.tokens {
            let _ = writeln!(out, "  --{}: {};", tok.name, tok.value);
        }
    }
    for (k, stack) in &t.font_families {
        let _ = writeln!(out, "  --font-{k}: {stack};");
    }
    out.push_str("}\n");
    // After `:root` (the same specificity), so a density's sizes win over the default ones.
    for d in &t.densities {
        let _ = writeln!(out, "[data-density=\"{}\"] {{", d.id);
        for tok in &d.tokens {
            let _ = writeln!(out, "  --{}: {};", tok.name, tok.value);
        }
        out.push_str("}\n");
    }
    for s in &t.type_styles {
        let mut decl = vec![
            format!("font-family: var(--font-{})", s.family),
            format!("font-size: {}", s.font_size),
            format!("line-height: {}", s.line_height),
            format!("font-weight: {}", s.font_weight),
        ];
        if let Some(ls) = &s.letter_spacing {
            decl.push(format!("letter-spacing: {ls}"));
        }
        let _ = writeln!(out, ".{} {{ {}; }}", s.name, decl.join("; "));
    }
    out
}

fn family<'a>(t: &'a Tokens, key: &str) -> Option<&'a Family> {
    t.families.iter().find(|f| f.key == key)
}

/// `theme.css`: Tailwind v4 `@theme inline` mapping onto the CSS variables.
///
/// `inline` makes utilities reference `var(--surface-0)` directly, so the `data-theme`
/// switch keeps working and `--font-ui` does not reference itself.
pub fn theme_css(t: &Tokens) -> String {
    let mut out = format!("/* {GENERATED} */\n@theme inline {{\n  --color-*: initial;\n");
    for c in &t.colors {
        let _ = writeln!(out, "  --color-{}: var(--{});", c.name, c.name);
    }
    for (key, prefix, ns) in [
        ("spacing", "space-", "spacing"),
        ("radius", "radius-", "radius"),
    ] {
        if let Some(f) = family(t, key) {
            for tok in &f.tokens {
                let short = tok.name.strip_prefix(prefix).unwrap_or(&tok.name);
                let _ = writeln!(out, "  --{ns}-{short}: var(--{});", tok.name);
            }
        }
    }
    for s in &t.shadows {
        let short = s.name.strip_prefix("shadow-").unwrap_or(&s.name);
        let _ = writeln!(out, "  --shadow-{short}: var(--{});", s.name);
    }
    for (k, _) in &t.font_families {
        let _ = writeln!(out, "  --font-{k}: var(--font-{k});");
    }
    out.push_str("}\n");
    out
}

fn ts_str(s: &str) -> String {
    format!("{s:?}")
}

fn pascal(s: &str) -> String {
    let mut c = s.chars();
    c.next()
        .map_or_else(String::new, |f| f.to_uppercase().chain(c).collect())
}

fn ts_union(name: &str, names: &[&str]) -> String {
    let mut s = format!("export type {name} =\n");
    for n in names {
        let _ = writeln!(s, "  | {}", ts_str(n));
    }
    s.truncate(s.trim_end().len());
    s.push_str(";\n");
    s
}

fn hex_of(c: Rgba) -> String {
    if c.a == 255 {
        format!("#{:02x}{:02x}{:02x}", c.r, c.g, c.b)
    } else {
        format!("#{:02x}{:02x}{:02x}{:02x}", c.r, c.g, c.b, c.a)
    }
}

/// `tokens.ts`: constants and string-literal unions for `@cutweave/tokens`.
pub fn tokens_ts(t: &Tokens) -> Result<String, String> {
    let mut o = format!(
        "// SPDX-License-Identifier: GPL-3.0-or-later\n// biome-ignore-all lint: generated file\n// biome-ignore-all format: generated file\n// {GENERATED}\n\n"
    );
    let theme_ids: Vec<&str> = t.themes.iter().map(String::as_str).collect();
    let list = |v: &[&str]| v.iter().map(|s| ts_str(s)).collect::<Vec<_>>().join(", ");
    let _ = writeln!(o, "/** Theme ids, `dark` first. */");
    let _ = writeln!(o, "export const themes = [{}] as const;", list(&theme_ids));
    o.push_str("export type ThemeId = (typeof themes)[number];\n\n");

    // Themed families: values resolved to concrete hex (colors) or CSS strings (shadows).
    o.push_str("/** Color values per theme, aliases resolved; 8-digit hex carries alpha. */\n");
    o.push_str("export const colors = {\n");
    for (ti, th) in t.themes.iter().enumerate() {
        let _ = writeln!(o, "  {}: {{", ts_str(th));
        for c in &t.colors {
            let hex = hex_of(t.resolve_color(&c.name, ti)?);
            let _ = writeln!(o, "    {}: {},", ts_str(&c.name), ts_str(&hex));
        }
        o.push_str("  },\n");
    }
    o.push_str("} as const;\n");
    let names: Vec<&str> = t.colors.iter().map(|c| c.name.as_str()).collect();
    o.push_str(&ts_union("ColorTokenName", &names));
    o.push('\n');

    if !t.shadows.is_empty() {
        o.push_str("/** Box-shadow strings per theme. */\nexport const shadow = {\n");
        for (ti, th) in t.themes.iter().enumerate() {
            let _ = writeln!(o, "  {}: {{", ts_str(th));
            for s in &t.shadows {
                let _ = writeln!(o, "    {}: {},", ts_str(&s.name), ts_str(&s.values[ti]));
            }
            o.push_str("  },\n");
        }
        o.push_str("} as const;\n");
        let names: Vec<&str> = t.shadows.iter().map(|c| c.name.as_str()).collect();
        o.push_str(&ts_union("ShadowTokenName", &names));
        o.push('\n');
    }

    for f in &t.families {
        if !f.key.chars().all(|c| c.is_ascii_alphanumeric()) {
            return Err(format!(
                "family key `{}` is not a valid TS identifier",
                f.key
            ));
        }
        let _ = writeln!(o, "/** `{}` tokens (theme independent). */", f.key);
        let _ = writeln!(o, "export const {} = {{", f.key);
        for tok in &f.tokens {
            let _ = writeln!(o, "  {}: {},", ts_str(&tok.name), ts_str(&tok.value));
        }
        o.push_str("} as const;\n");
        let names: Vec<&str> = f.tokens.iter().map(|c| c.name.as_str()).collect();
        o.push_str(&ts_union(&format!("{}TokenName", pascal(&f.key)), &names));
        o.push('\n');
    }

    if !t.densities.is_empty() {
        o.push_str("/** The tokens each density makes larger (`data-density` on the root). */\n");
        o.push_str("export const density = {\n");
        for d in &t.densities {
            let _ = writeln!(o, "  {}: {{", ts_str(&d.id));
            for tok in &d.tokens {
                let _ = writeln!(o, "    {}: {},", ts_str(&tok.name), ts_str(&tok.value));
            }
            o.push_str("  },\n");
        }
        o.push_str("} as const;\n");
        let ids: Vec<&str> = t.densities.iter().map(|d| d.id.as_str()).collect();
        o.push_str(&ts_union("DensityId", &ids));
        o.push('\n');
    }

    o.push_str("/** Font stacks by key (CSS `--font-<key>`). */\nexport const fontFamilies = {\n");
    for (k, v) in &t.font_families {
        let _ = writeln!(o, "  {}: {},", ts_str(k), ts_str(v));
    }
    o.push_str("} as const;\n");
    let keys: Vec<&str> = t.font_families.iter().map(|(k, _)| k.as_str()).collect();
    o.push_str(&ts_union("FontFamilyKey", &keys));
    o.push('\n');

    o.push_str("/** Type styles (CSS classes of the same name). */\nexport const typeStyles = {\n");
    for s in &t.type_styles {
        let _ = write!(
            o,
            "  {}: {{ family: {}, fontSize: {}, lineHeight: {}, fontWeight: {}",
            ts_str(&s.name),
            ts_str(&s.family),
            ts_str(&s.font_size),
            ts_str(&s.line_height),
            ts_str(&s.font_weight)
        );
        if let Some(ls) = &s.letter_spacing {
            let _ = write!(o, ", letterSpacing: {}", ts_str(ls));
        }
        o.push_str(" },\n");
    }
    o.push_str("} as const;\n");
    let names: Vec<&str> = t.type_styles.iter().map(|c| c.name.as_str()).collect();
    o.push_str(&ts_union("TypeStyleName", &names));
    o.push('\n');

    o.push_str(
        "/** The CSS custom property reference for a token name, e.g. `var(--surface-0)`. */\n",
    );
    o.push_str(
        "export const cssVar = <N extends string>(name: N): `var(--${N})` => `var(--${name})`;\n",
    );
    Ok(o)
}

fn srgb_to_linear(c: u8) -> f32 {
    let c = f64::from(c) / 255.0;
    let l = if c <= 0.04045 {
        c / 12.92
    } else {
        ((c + 0.055) / 1.055).powf(2.4)
    };
    #[allow(clippy::cast_possible_truncation)]
    {
        l as f32
    }
}

fn rust_const_name(name: &str) -> String {
    name.replace('-', "_").to_ascii_uppercase()
}

fn px(value: &str, name: &str) -> Result<f32, String> {
    value
        .strip_suffix("px")
        .and_then(|n| n.parse::<f32>().ok())
        .ok_or_else(|| format!("{name}: `{value}` is not a px length"))
}

/// `generated.rs` for the `cutweave-tokens` crate.
pub fn tokens_rs(t: &Tokens) -> Result<String, String> {
    let mut o = format!(
        "// SPDX-License-Identifier: GPL-3.0-or-later\n// {GENERATED}\n\n#![allow(clippy::unreadable_literal)]\n\n"
    );
    for (ti, th) in t.themes.iter().enumerate() {
        let _ = writeln!(o, "/// Colors of the `{th}` theme.");
        let _ = writeln!(o, "pub mod {th} {{");
        o.push_str("    use crate::Color;\n\n");
        for c in &t.colors {
            let rgba = t.resolve_color(&c.name, ti)?;
            let lin = [
                srgb_to_linear(rgba.r),
                srgb_to_linear(rgba.g),
                srgb_to_linear(rgba.b),
                f32::from(rgba.a) / 255.0,
            ];
            let _ = writeln!(o, "    /// `{}`: {}", c.name, hex_of(rgba));
            let _ = writeln!(
                o,
                "    pub const {}: Color = Color {{\n        srgb: [{}, {}, {}, {}],\n        linear: [{:?}, {:?}, {:?}, {:?}],\n    }};",
                rust_const_name(&c.name),
                rgba.r,
                rgba.g,
                rgba.b,
                rgba.a,
                lin[0],
                lin[1],
                lin[2],
                lin[3]
            );
        }
        o.push_str("\n    /// Every color of the theme by token name, in token-file order.\n");
        o.push_str("    pub const ALL: &[(&str, Color)] = &[\n");
        for c in &t.colors {
            let _ = writeln!(o, "        ({:?}, {}),", c.name, rust_const_name(&c.name));
        }
        o.push_str("    ];\n}\n\n");
    }
    for (key, module, doc) in [
        ("spacing", "spacing", "Spacing scale in px."),
        ("radius", "radius", "Corner radii in px."),
    ] {
        let f = family(t, key).ok_or_else(|| format!("tokens.json has no `{key}` family"))?;
        let _ = writeln!(o, "/// {doc}\npub mod {module} {{");
        for tok in &f.tokens {
            let _ = writeln!(
                o,
                "    /// `{}`: {}\n    pub const {}: f32 = {:?};",
                tok.name,
                tok.value,
                rust_const_name(&tok.name),
                px(&tok.value, &tok.name)?
            );
        }
        o.push_str("}\n\n");
    }
    o.truncate(o.trim_end().len());
    o.push('\n');
    Ok(o)
}

#[cfg(test)]
mod tests {
    use super::*;

    const MINI: &str = r##"{
      "name": "Mini", "version": 1,
      "color": {"themes": [{"id": "dark"}, {"id": "light"}], "tokens": [
        {"name": "bg", "value": {"dark": "#111111", "light": "#EEEEEE"}, "usage": ""},
        {"name": "gold", "value": "#f2b33d", "usage": ""},
        {"name": "playhead", "value": "{gold}", "usage": ""},
        {"name": "wash", "value": {"dark": "#f2b33d24", "light": "#f2b33d33"}, "usage": ""}
      ]},
      "spacing": {"tokens": [{"name": "space-1", "value": "4px", "usage": ""}]},
      "radius": {"tokens": [{"name": "radius-sm", "value": "4px", "usage": ""}]},
      "shadow": {"tokens": [{"name": "shadow-pop", "value": {"dark": "0 1px #000", "light": "0 1px #fff"}, "usage": ""}]},
      "zIndex": {"tokens": [{"name": "z-top", "value": "20", "usage": ""}]},
      "density": {"sets": [{"id": "roomy", "tokens": [
        {"name": "space-1", "value": "6px", "usage": "u"}
      ]}]},
      "type": {"families": {"ui": "\"Inter\", sans-serif"}, "groups": [
        {"name": "UI", "family": "ui", "styles": [
          {"name": "body", "fontSize": "13px", "lineHeight": "20px", "fontWeight": 400},
          {"name": "tag", "fontSize": "11px", "lineHeight": "16px", "fontWeight": 600, "letterSpacing": "0.04em"}
        ]}
      ]}
    }"##;

    fn mini() -> Tokens {
        Tokens::parse(MINI).unwrap()
    }

    #[test]
    fn css_snapshot() {
        let expected = "\
/* Mini \u{2014} generated from tokens.json */
:root, [data-theme=\"dark\"] {
  --bg: #111111;
  --gold: #f2b33d;
  --playhead: var(--gold);
  --wash: #f2b33d24;
  --shadow-pop: 0 1px #000;
}
[data-theme=\"light\"] {
  --bg: #eeeeee;
  --gold: #f2b33d;
  --playhead: var(--gold);
  --wash: #f2b33d33;
  --shadow-pop: 0 1px #fff;
}
:root {
  --space-1: 4px;
  --radius-sm: 4px;
  --z-top: 20;
  --font-ui: \"Inter\", sans-serif;
}
[data-density=\"roomy\"] {
  --space-1: 6px;
}
.body { font-family: var(--font-ui); font-size: 13px; line-height: 20px; font-weight: 400; }
.tag { font-family: var(--font-ui); font-size: 11px; line-height: 16px; font-weight: 600; letter-spacing: 0.04em; }
";
        assert_eq!(tokens_css(&mini()), expected);
    }

    #[test]
    fn theme_snapshot() {
        let expected = "\
/* generated by `cargo xtask tokens` from design/tokens.json; do not edit */
@theme inline {
  --color-*: initial;
  --color-bg: var(--bg);
  --color-gold: var(--gold);
  --color-playhead: var(--playhead);
  --color-wash: var(--wash);
  --spacing-1: var(--space-1);
  --radius-sm: var(--radius-sm);
  --shadow-pop: var(--shadow-pop);
  --font-ui: var(--font-ui);
}
";
        assert_eq!(theme_css(&mini()), expected);
    }

    #[test]
    fn ts_resolves_aliases_and_emits_unions() {
        let ts = tokens_ts(&mini()).unwrap();
        assert!(ts.contains("export const themes = [\"dark\", \"light\"] as const;"));
        assert!(ts.contains("    \"playhead\": \"#f2b33d\","));
        assert!(ts.contains("    \"wash\": \"#f2b33d24\","));
        assert!(ts.contains("export type ColorTokenName =\n  | \"bg\"\n  | \"gold\""));
        assert!(ts.contains("export type ZIndexTokenName =\n  | \"z-top\";"));
        assert!(ts.contains("\"tag\": { family: \"ui\""));
        assert!(ts.contains(
            "export const density = {\n  \"roomy\": {\n    \"space-1\": \"6px\",\n  },\n} as const;"
        ));
        assert!(ts.contains("export type DensityId =\n  | \"roomy\";"));
    }

    #[test]
    fn rust_snapshot_fragments() {
        let rs = tokens_rs(&mini()).unwrap();
        assert!(rs.contains("pub mod dark {"));
        assert!(rs.contains("pub mod light {"));
        assert!(rs.contains("/// `wash`: #f2b33d24"));
        assert!(rs.contains("srgb: [242, 179, 61, 36],"));
        assert!(rs.contains("pub const SPACE_1: f32 = 4.0;"));
        assert!(rs.contains("pub const RADIUS_SM: f32 = 4.0;"));
        assert!(rs.contains("(\"playhead\", PLAYHEAD),"));
    }

    #[test]
    fn emitters_are_deterministic() {
        let a = mini();
        let b = mini();
        assert_eq!(tokens_css(&a), tokens_css(&b));
        assert_eq!(theme_css(&a), theme_css(&b));
        assert_eq!(tokens_ts(&a).unwrap(), tokens_ts(&b).unwrap());
        assert_eq!(tokens_rs(&a).unwrap(), tokens_rs(&b).unwrap());
    }
}
